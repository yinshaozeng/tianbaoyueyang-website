/**
 * 获取当前语言的翻译文本
 * @param {string} locale - 语言代码
 * @param {string} key - 翻译键（支持点分隔的嵌套键，如 'nav.home'）
 * @returns {string} 翻译文本
 */
export function t(locale, key) {
  const keys = key.split('.')
  let value = messages[locale]

  for (const k of keys) {
    if (value && typeof value === 'object') {
      value = value[k]
    } else {
      return key // 如果找不到翻译，返回键本身
    }
  }

  return value || key
}
